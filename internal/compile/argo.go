// Argo renders a basic script as an Argo Workflows WorkflowTemplate: one DAG
// with a task for each step, asked once for each kind of event as the GitHub
// target is.
//
// A task runs in the step's own image, as a pod: an init container (o.InitImage,
// which holds starci) runs `starci pod prepare`, which checks out only the
// step's inputs, fetches what it is handed and its tools by checksum, and asks
// the shared store whether it passed before (step.PreparePod); the
// step's services are native sidecars (init containers that keep running, held
// to their `ready` by a startup probe), and the command runs in the main
// container. Nothing here needs Docker, which a cluster rarely allows.
//
// What a step does not carry over is refused, not dropped, wherever a pod
// could not keep to it: see argoRefusal.
func Argo(filename string, src []byte, o Options) (string, error) {
	if o.DefaultBranch == "" {
		o.DefaultBranch = "main"
	}
	if o.Arch == "" {
		o.Arch = "amd64"
	}
	if o.Name == "" {
		o.Name = "starci"
	}
	if o.InitImage == "" {
		return "", fmt.Errorf("the Argo target needs --init-image: an image with starci and git, which puts each step's inputs, artifacts and tools in place (dev/argo-init.Dockerfile builds one). starci names none")
	}
	u, err := eventUnion(filename, src, o)
	if err != nil {
		return "", err
	}
	merged := &plan.Plan{Steps: u.steps}
	if err := merged.Validate(); err != nil {
		return "", err
	}
	for _, s := range u.steps {
		if err := argoRefusal(s, o); err != nil {
			return "", err
		}
	}
	ids := argoIDs(u.steps)

	notes := u.notes(o.DefaultBranch)
	var placed []string
	remembers := false
	for _, s := range u.steps {
		remembers = remembers || s.Cache
		if len(s.Caches) > 0 {
			placed = append(placed, s.Name)
		}
	}
	if remembers {
		notes = append(notes, "A step with cache = True is skipped when it passed before with the same inputs, if the `store` parameter names a shared store (STARCI_STORE, as for a machine); without one every step runs every time. The pods then need the store's credentials from the cluster. A pass is keyed on the step's image by name: a tag that moves does not run it again.")
	}
	if keepsArtifacts(merged) {
		notes = append(notes, "Artifacts go from pod to pod through the shared store, so a run that keeps or is handed one needs the `store` parameter; their pointers travel as each task's `kept` output parameter. A task skipped because it passed before hands on what it kept then.")
	}
	if len(placed) > 0 {
		notes = append(notes, fmt.Sprintf("A step's caches (%s) are directories of the pod and are gone when it ends.", strings.Join(placed, ", ")))
	}
	if len(u.schedules) > 0 {
		notes = append(notes, "A schedule is a CronWorkflow you create from this template, with the `event` parameter set to schedule and `schedule` to its name. Overlap and catch-up are Argo's to decide.")
	}
	if quiet := u.quiet(); len(quiet) > 0 {
		notes = append(notes, "The script plans nothing for "+join(quiet)+", so a run for "+pronoun(len(quiet))+" does nothing and passes.")
	}
	notes = append(notes, "A step that fails fails its pod and is not run again; a pod lost to its node is tried again, twice. Steps that need a failed step are omitted by Argo, not skipped.")

	var tasks []any
	for _, s := range u.steps {
		t, err := argoTask(s, ids, u.condition(s.Name, argoPush, argoPR, func(p probe) string { return p.argoWhen }), o)
		if err != nil {
			return "", err
		}
		tasks = append(tasks, t)
	}

	param := func(name, def string) any {
		if def == "" && name != "clone_url" && name != "sha" {
			return obj{{"name", name}, {"value", ""}}
		}
		if name == "clone_url" || name == "sha" {
			return obj{{"name", name}}
		}
		return obj{{"name", name}, {"value", def}}
	}
	doc := obj{
		{"apiVersion", "argoproj.io/v1alpha1"},
		{"kind", "WorkflowTemplate"},
		{"metadata", obj{{"name", o.Name}}},
		{"spec", obj{
			{"entrypoint", "ci"},
			{"arguments", obj{{"parameters", []any{
				param("clone_url", ""), param("sha", ""),
				param("event", "push"), param("ref", ""), param("tag", ""), param("schedule", ""), param("fork", "false"), param("store", ""),
			}}}},
			{"templates", []any{obj{
				{"name", "ci"},
				{"dag", obj{{"tasks", tasks}}},
			}}},
		}},
	}

	var w strings.Builder
	source := o.Source
	if source == "" {
		source = "a starci script"
	}
	fmt.Fprintf(&w, "# Generated by `starci compile --target argo` from %s. Edit that, not this.\n", source)
	fmt.Fprintf(&w, "#\n# Each task is one step of the plan: a pod in the step's image, given only the\n# step's inputs and tools. The init container image is\n# %s.\n", o.InitImage)
	fmt.Fprintf(&w, "#\n#   kubectl apply -n NAMESPACE -f THIS-FILE\n#   argo submit -n NAMESPACE --from workflowtemplate/%s -p clone_url=URL -p sha=SHA \\\n#     [-p event=push|tag|pull_request|schedule|manual -p ref=BRANCH -p tag=NAME -p fork=true]\n", o.Name)
	w.WriteString("#\n# What does not carry over:\n")
	for _, n := range notes {
		for i, line := range wrap(n, 74) {
			if i == 0 {
				w.WriteString("#  - " + line + "\n")
			} else {
				w.WriteString("#    " + line + "\n")
			}
		}
	}
	w.WriteString("\n")
	return w.String() + strings.Join(yamlLines(doc, 0), "\n") + "\n", nil
}

// argoWorkflowsVersion is the Argo Workflows release the files were checked
// against: its types and its validator accept them (see argo_test.go).
const argoWorkflowsVersion = "v3.7.18"

const (
	argoPush = "workflow.parameters.event == 'push'"
	argoPR   = "workflow.parameters.event == 'pull_request'"
)

// templated finds what Argo would substitute in text: there is no way to write
// "{{" in a template, so a step that has it cannot be compiled.
var templated = regexp.MustCompile(`\{\{`)

// argoRefusal says why a step cannot be a pod, if it cannot.
func argoRefusal(s plan.Step, o Options) error {
	no := func(why string) error {
		return fmt.Errorf("step %q %s, which the Argo target cannot carry over", s.Name, why)
	}
	switch {
	case s.Offline:
		return no("sets network = False: a pod's network policy covers the whole pod, including the container that fetches its inputs")
	case len(s.Packages) > 0:
		return no("lists packages: installing them needs root and the network, and an image cannot be built without privilege")
	case s.Bare() && o.BareImage == "":
		return no("has no image: give --bare-image, the image such steps run in")
	}
	for _, sv := range s.Services {
		if len(sv.Files) > 0 {
			return no(fmt.Sprintf("gives service %q files from the repository: a pod has nowhere to put them yet", sv.Name))
		}
	}
	texts := []string{s.Name, s.Run, strings.Join(s.Argv, " ")}
	for _, v := range s.Env {
		texts = append(texts, v)
	}
	for _, sv := range s.Services {
		texts = append(texts, sv.Ready, strings.Join(sv.Args, " "), sv.Image)
		for _, v := range sv.Env {
			texts = append(texts, v)
		}
	}
	for _, t := range texts {
		if templated.MatchString(t) {
			return no("contains \"{{\", which Argo would read as its own template")
		}
	}
	return nil
}

var notNameChar = regexp.MustCompile(`[^a-z0-9-]+`)

// argoIDs gives each step a task name Kubernetes accepts, unique in the DAG.
func argoIDs(steps []plan.Step) map[string]string {
	ids, taken := map[string]string{}, map[string]bool{}
	for _, s := range steps {
		id := strings.Trim(notNameChar.ReplaceAllString(strings.ToLower(s.Name), "-"), "-")
		if id == "" || (id[0] >= '0' && id[0] <= '9') {
			id = "step-" + id
		}
		base := id
		for n := 2; taken[id]; n++ {
			id = fmt.Sprintf("%s-%d", base, n)
		}
		taken[id] = true
		ids[s.Name] = id
	}
	return ids
}

// nodeLabel is the label a machine property is on a Kubernetes node.
func nodeLabel(k string) string {
	switch k {
	case "os":
		return "kubernetes.io/os"
	case "arch":
		return "kubernetes.io/arch"
	}
	return k
}

func argoTask(s plan.Step, ids map[string]string, cond string, o Options) (any, error) {
	task := obj{{"name", ids[s.Name]}}
	if len(s.Needs) > 0 {
		var needs []string
		for _, n := range s.Needs {
			needs = append(needs, ids[n])
		}
		// Argo's default reading of a dependency is that it succeeded or was
		// skipped, which is the plan's: a step this event does not plan lets
		// what needs it go ahead, and a failed one omits what needs it.
		task = append(task, kv{"dependencies", strs(needs)})
	}
	if cond != "" {
		task = append(task, kv{"when", "{{=" + cond + "}}"})
	}

	image := s.Image
	if s.Bare() {
		image = o.BareImage
	}

	// Where the step runs.
	selector := obj{}
	for _, k := range sortedKeys(s.On) {
		selector = append(selector, kv{nodeLabel(k), s.On[k]})
	}
	if len(s.Tools) > 0 && s.On["arch"] == "" {
		selector = append(selector, kv{"kubernetes.io/arch", o.Arch})
	}
	tmpl := obj{}
	if len(selector) > 0 {
		tmpl = append(tmpl, kv{"nodeSelector", selector})
	}
	if aff := argoAffinity(s); aff != nil {
		tmpl = append(tmpl, kv{"affinity", aff})
	}
	tmpl = append(tmpl, kv{"retryStrategy", obj{{"limit", 2}, {"retryPolicy", "OnError"}}})

	// What the pod holds. /opt/starci is what the init container leaves the
	// main one (step.PreparePod): the tools, whether the step passed before,
	// and starci, to finish a step that keeps something or remembers passes.
	volumes := []any{obj{{"name", "workspace"}, {"emptyDir", obj{}}}, obj{{"name", "starci"}, {"emptyDir", obj{}}}}
	mounts := []any{obj{{"name", "workspace"}, {"mountPath", "/workspace"}}}
	var cacheMounts []any
	for _, name := range sortedKeys(s.Caches) {
		vol := "cache-" + notNameChar.ReplaceAllString(strings.ToLower(name), "-")
		volumes = append(volumes, obj{{"name", vol}, {"emptyDir", obj{}}})
		cacheMounts = append(cacheMounts, obj{{"name", vol}, {"mountPath", s.Caches[name]}})
	}

	// Prepare: starci, in the init image, does for the pod what a machine
	// does before a step, with the same code: only the step's inputs, what it
	// is handed, its tools by checksum, and whether it passed before.
	for _, t := range s.Tools {
		if _, ok := t.Sum("linux/" + o.Arch); !ok {
			return nil, fmt.Errorf("step %q: tool %q has no build for %s, which is what the cluster's nodes are (--arch)", s.Name, t.Name, o.Arch)
		}
	}
	embedded := s
	embedded.Image = image
	stepJSON, err := jsonText(embedded)
	if err != nil {
		return nil, err
	}
	stepEnv := []any{obj{{"name", "STARCI_STEP"}, {"value", stepJSON}}}
	if len(s.Artifacts) > 0 {
		stepEnv = append(stepEnv, obj{{"name", "STARCI_GIVEN"}, {"value", "{{inputs.parameters.given}}"}})
	}
	storeEnv := func(state string) []any {
		return []any{
			obj{{"name", "STARCI_STORE"}, {"value", "{{workflow.parameters.store}}"}},
			obj{{"name", "STARCI_STATE"}, {"value", state}},
		}
	}
	prepareEnv := []any{
		obj{{"name", "STARCI_CLONE_URL"}, {"value", "{{workflow.parameters.clone_url}}"}},
		obj{{"name", "STARCI_SHA"}, {"value", "{{workflow.parameters.sha}}"}},
		obj{{"name", "STARCI_ARCH"}, {"value", o.Arch}},
	}
	prepareEnv = append(append(prepareEnv, stepEnv...), storeEnv("/opt/starci/state")...)
	inits := []any{obj{
		{"name", "starci-prepare"},
		{"image", o.InitImage},
		{"command", strs([]string{"starci", "pod", "prepare"})},
		{"env", prepareEnv},
		{"volumeMounts", []any{
			obj{{"name", "workspace"}, {"mountPath", "/workspace"}},
			obj{{"name", "starci"}, {"mountPath", "/opt/starci"}},
		}},
	}}

	// Services: native sidecars, so that the step starts when they are ready
	// and they end when it does. They answer to their names on 127.0.0.1.
	var aliases []string
	for _, sv := range s.Services {
		aliases = append(aliases, sv.Name)
		c := obj{
			{"name", "service-" + notNameChar.ReplaceAllString(strings.ToLower(sv.Name), "-")},
			{"image", sv.Image},
			{"restartPolicy", "Always"},
		}
		if len(sv.Args) > 0 {
			c = append(c, kv{"args", strs(sv.Args)})
		}
		if len(sv.Env) > 0 {
			var env []any
			for _, k := range sortedKeys(sv.Env) {
				env = append(env, obj{{"name", k}, {"value", sv.Env[k]}})
			}
			c = append(c, kv{"env", env})
		}
		if sv.Ready != "" {
			within := 120
			if sv.ReadyWithin > 0 {
				within = sv.ReadyWithin
			}
			c = append(c, kv{"startupProbe", obj{
				{"exec", obj{{"command", strs([]string{"sh", "-c", sv.Ready})}}},
				{"periodSeconds", 1},
				{"timeoutSeconds", 10},
				{"failureThreshold", within},
			}})
		}
		inits = append(inits, c)
	}
	tmpl = append(tmpl, kv{"volumes", volumes}, kv{"initContainers", inits})
	if len(aliases) > 0 {
		tmpl = append(tmpl, kv{"hostAliases", []any{obj{{"ip", "127.0.0.1"}, {"hostnames", strs(aliases)}}}})
	}

	// The step itself. Tools go in front of the image's own PATH, which only
	// the container can say; a step that keeps something or remembers its
	// passes is finished by starci once it has passed (step.FinishPod).
	main := obj{{"name", "main"}, {"image", image}, {"workingDir", "/workspace"}}
	var env []any
	for _, k := range sortedKeys(s.Env) {
		if k == "PATH" && len(s.Tools) > 0 {
			continue
		}
		env = append(env, obj{{"name", k}, {"value", s.Env[k]}})
	}
	finish := s.Cache || len(s.Keep) > 0
	switch {
	case finish || len(s.Tools) > 0:
		var script strings.Builder
		if s.Cache {
			script.WriteString("if [ -e /opt/starci/hit ]; then\n  echo 'starci: passed before with the same inputs; not run again'\n")
			if len(s.Keep) > 0 {
				// What it kept then is handed on as if it had kept it now.
				script.WriteString("  cp /opt/starci/kept.json /tmp/starci-kept.json\n")
			}
			script.WriteString("  exit 0\nfi\n")
		}
		if len(s.Tools) > 0 {
			base := "$PATH"
			if p, ok := s.Env["PATH"]; ok {
				base = shq(p)
			}
			script.WriteString("PATH=\"$(cat /opt/starci/path):\"" + base + "; export PATH\n")
		}
		if finish {
			script.WriteString("(\n" + execCommand(s) + "\n)\nrc=$?\n" +
				"if [ \"$rc\" -eq 0 ]; then /opt/starci/starci pod finish || exit 1; fi\nexit $rc")
			env = append(append(env, stepEnv...), storeEnv("/tmp/starci-state")...)
		} else {
			script.WriteString(execCommand(s))
		}
		main = append(main, kv{"command", strs([]string{"sh", "-c"})}, kv{"args", strs([]string{script.String()})})
	case len(s.Argv) > 0:
		main = append(main, kv{"command", strs(s.Argv)})
	default:
		main = append(main, kv{"command", strs([]string{"sh", "-c"})}, kv{"args", strs([]string{s.Run})})
	}
	if len(env) > 0 {
		main = append(main, kv{"env", env})
	}
	all := append(append([]any{}, mounts...), cacheMounts...)
	all = append(all, obj{{"name", "starci"}, {"mountPath", "/opt/starci"}, {"readOnly", true}})
	main = append(main, kv{"volumeMounts", all})
	tmpl = append(tmpl, kv{"container", main})

	// What it keeps leaves as the pointers starci wrote, and what it is
	// handed arrives as the pointers the steps it needs left.
	if len(s.Keep) > 0 {
		tmpl = append(tmpl, kv{"outputs", obj{{"parameters", []any{obj{
			{"name", "kept"},
			{"valueFrom", obj{{"path", "/tmp/starci-kept.json"}, {"default", "{}"}}},
		}}}}})
	}
	if len(s.Artifacts) > 0 {
		var parts []string
		for _, from := range handedFrom(s) {
			name, _ := json.Marshal(from)
			parts = append(parts, fmt.Sprintf("%s:{{tasks.%s.outputs.parameters.kept}}", name, ids[from]))
		}
		task = append(task, kv{"arguments", obj{{"parameters", []any{obj{{"name", "given"}, {"value", "{" + strings.Join(parts, ",") + "}"}}}}}})
		tmpl = append(obj{{"inputs", obj{{"parameters", []any{obj{{"name", "given"}}}}}}}, tmpl...)
	}
	return append(task, kv{"inline", tmpl}), nil
}

// execCommand is the step's command, to follow the shell that sets PATH up or
// to sit in a subshell. A command given as a list is run as the shell's last
// command, without a shell of its own.
func execCommand(s plan.Step) string {
	if len(s.Argv) > 0 {
		return "exec " + s.Command()
	}
	return s.Run
}

// jsonText is v as JSON, without HTML escaping.
func jsonText(v any) (string, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return "", err
	}
	return strings.TrimSuffix(b.String(), "\n"), nil
}

// argoAffinity says where a step would like to be and must not be: `prefer`
// as a preference, and `avoid` as a requirement, unlike the targets that have
// no such thing and drop them.
func argoAffinity(s plan.Step) obj {
	var node obj
	if len(s.Prefer) > 0 {
		var prefs []any
		for _, k := range sortedKeys(s.Prefer) {
			prefs = append(prefs, obj{
				{"weight", 1},
				{"preference", obj{{"matchExpressions", []any{obj{{"key", nodeLabel(k)}, {"operator", "In"}, {"values", strs([]string{s.Prefer[k]})}}}}}},
			})
		}
		node = append(node, kv{"preferredDuringSchedulingIgnoredDuringExecution", prefs})
	}
	if len(s.Avoid) > 0 {
		var exprs []any
		for _, k := range sortedKeys(s.Avoid) {
			exprs = append(exprs, obj{{"key", nodeLabel(k)}, {"operator", "NotIn"}, {"values", strs([]string{s.Avoid[k]})}})
		}
		node = append(node, kv{"requiredDuringSchedulingIgnoredDuringExecution", obj{{"nodeSelectorTerms", []any{obj{{"matchExpressions", exprs}}}}}})
	}
	if node == nil {
		return nil
	}
	return obj{{"nodeAffinity", node}}
}
