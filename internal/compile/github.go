// Package compile turns a basic plan into something another CI system can
// run, for places where starci itself is not running.
package compile

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"path"
	"regexp"
	"sort"
	"strings"

	"git.phin.tech/sam/starci/internal/plan"
)

// Options are the choices a workflow needs that a plan does not carry.
type Options struct {
	// Source is the script the plan came from, named in the header.
	Source string
	// RunsOn is the runner for steps that do not ask for particular workers.
	RunsOn string
	// Arch is the architecture those runners have, which decides which build
	// of each tool is downloaded: amd64 or arm64.
	Arch string
	// Read lists the fields of ctx the script read. A plan that depends on
	// the commit cannot be frozen faithfully, and the header says so.
	Read []string
	// DefaultBranch is the branch "is this the default branch?" is asked of.
	DefaultBranch string

	// The rest are filled in when compiling for several events.

	// on is the workflow's trigger block, already written out.
	on string
	// conditions gives, for a step that does not run on every event, the
	// expression that says when it does.
	conditions map[string]string
	// notes are extra lines for the header.
	notes []string
}

// GitHub renders a plan as a GitHub Actions workflow. Forgejo and Gitea
// Actions read the same format.
//
// Each step becomes a job that does what a starci worker does: check out only
// the step's inputs, fetch its tools by checksum, build an image with its
// packages, and run its command in that container. A job whose inputs are
// unchanged since it last passed skips the work, using the Actions cache as
// the record of passes.
//
// What does not carry over is said in the header of the file it writes.
func GitHub(p *plan.Plan, o Options) (string, error) {
	if o.RunsOn == "" {
		o.RunsOn = "ubuntu-latest"
	}
	if o.Arch == "" {
		o.Arch = "amd64"
	}
	if err := p.Validate(); err != nil {
		return "", err
	}

	ids := jobIDs(p.Steps)
	var w strings.Builder
	header(&w, p, o)
	on := o.on
	if on == "" {
		on = "on:\n  push:\n  pull_request:\n"
	}
	w.WriteString("name: CI\n\n" + on + "\njobs:\n")
	for i, s := range p.Steps {
		if i > 0 {
			w.WriteString("\n")
		}
		if err := job(&w, s, ids, o); err != nil {
			return "", err
		}
	}
	return w.String(), nil
}

func header(w *strings.Builder, p *plan.Plan, o Options) {
	notes := append(commitNote(o), o.notes...)
	var unplaceable []string
	for _, s := range p.Steps {
		if len(s.Prefer) > 0 || len(s.Avoid) > 0 {
			unplaceable = append(unplaceable, s.Name)
		}
	}
	if len(unplaceable) > 0 {
		notes = append(notes, fmt.Sprintf("`prefer` and `avoid` have no equivalent here and are dropped (%s). `worker` becomes runner labels.", strings.Join(unplaceable, ", ")))
	}
	notes = append(notes, "Passes are remembered in this repository's Actions cache, which GitHub scopes by branch and evicts when old. starci's own store has neither limit.")
	writeHeader(w, "starci compile", o, notes)
}

// commitNote is the warning owed whenever a script's plan depends on the
// commit, which no fixed file can reproduce.
func commitNote(o Options) []string {
	if len(o.Read) == 0 {
		return nil
	}
	return []string{fmt.Sprintf("The script reads ctx.%s, so its plan depends on the commit. This file is the plan for a commit about which nothing is known, and is the same for every push: steps the script would add or drop for a particular branch or set of changed files are not represented.", strings.Join(o.Read, ", ctx."))}
}

func writeHeader(w *strings.Builder, command string, o Options, notes []string) {
	source := o.Source
	if source == "" {
		source = "a starci script"
	}
	fmt.Fprintf(w, "# Generated by `%s` from %s. Edit that, not this.\n", command, source)
	w.WriteString("#\n# Each job is one step of the plan: the same image, command, tools and\n# packages, given only the step's inputs. A job skips its work when it has\n# already passed with the same inputs.\n")
	w.WriteString("#\n# What does not carry over:\n")
	for _, n := range notes {
		for i, line := range wrap(n, 74) {
			if i == 0 {
				w.WriteString("#  - " + line + "\n")
			} else {
				w.WriteString("#    " + line + "\n")
			}
		}
	}
	w.WriteString("\n")
}

var notIDChar = regexp.MustCompile(`[^a-z0-9_-]+`)

// jobIDs gives each step an id GitHub accepts, unique within the workflow.
func jobIDs(steps []plan.Step) map[string]string {
	ids, taken := map[string]string{}, map[string]bool{}
	for _, s := range steps {
		id := strings.Trim(notIDChar.ReplaceAllString(strings.ToLower(s.Name), "-"), "-")
		if id == "" || (id[0] >= '0' && id[0] <= '9') {
			id = "step-" + id
		}
		base := id
		for n := 2; taken[id]; n++ {
			id = fmt.Sprintf("%s-%d", base, n)
		}
		taken[id] = true
		ids[s.Name] = id
	}
	return ids
}

func job(w *strings.Builder, s plan.Step, ids map[string]string, o Options) error {
	id := ids[s.Name]
	fmt.Fprintf(w, "  %s:\n    name: %s\n", id, q(s.Name))

	if len(s.Worker) > 0 {
		labels := []string{"self-hosted"}
		for _, k := range sortedKeys(s.Worker) {
			labels = append(labels, k+"="+s.Worker[k])
		}
		fmt.Fprintf(w, "    runs-on: [%s]\n", strings.Join(quoteAll(labels), ", "))
	} else {
		fmt.Fprintf(w, "    runs-on: %s\n", o.RunsOn)
	}
	// A job that needs one which does not run on this event would be skipped
	// along with it. Asking only that nothing failed lets it run.
	waitsOnConditional := false
	if len(s.Needs) > 0 {
		var needs []string
		for _, n := range s.Needs {
			needs = append(needs, ids[n])
			waitsOnConditional = waitsOnConditional || o.conditions[n] != ""
		}
		fmt.Fprintf(w, "    needs: [%s]\n", strings.Join(needs, ", "))
	}
	switch cond := o.conditions[s.Name]; {
	case waitsOnConditional && cond != "":
		fmt.Fprintf(w, "    if: ${{ !failure() && !cancelled() && (%s) }}\n", cond)
	case waitsOnConditional:
		w.WriteString("    if: ${{ !failure() && !cancelled() }}\n")
	case cond != "":
		fmt.Fprintf(w, "    if: ${{ %s }}\n", cond)
	}
	w.WriteString("    steps:\n")

	// Only the inputs are checked out, which is as close as a workflow gets
	// to a step that cannot see anything else.
	w.WriteString("      - uses: actions/checkout@v4\n")
	whole := len(s.Inputs) == 1 && s.Inputs[0] == "."
	if !whole {
		w.WriteString("        with:\n          sparse-checkout-cone-mode: false\n          sparse-checkout: |\n")
		for _, in := range s.Inputs {
			fmt.Fprintf(w, "            %s\n", sparsePattern(in))
		}
	}

	skip := ""
	if s.Cache {
		skip = "        if: steps.passed.outputs.cache-hit != 'true'\n"
		fmt.Fprintf(w, "      - name: Has this already passed with these inputs?\n        id: passed\n        uses: actions/cache@v4\n        with:\n          path: ${{ runner.temp }}/starci-passed\n          key: starci-passed-%s-%s-${{ hashFiles(%s) }}\n",
			id, stepKey(s, o.Arch), strings.Join(hashGlobs(s.Inputs), ", "))
	}

	var mounts, pathDirs []string
	for _, t := range s.Tools {
		sum, ok := t.SHA256[o.Arch]
		if !ok {
			return fmt.Errorf("step %q: tool %q has no build for %s, which is what %s runners are", s.Name, t.Name, o.Arch, o.RunsOn)
		}
		arch := o.Arch
		if name, ok := t.ArchNames[o.Arch]; ok {
			arch = name
		}
		fill := func(v string) string { return strings.ReplaceAll(v, "{arch}", arch) }
		dir := "$RUNNER_TEMP/starci-tools/" + t.Name
		fmt.Fprintf(w, "      - name: %s\n%s        run: |\n", q("Tool: "+t.Name), skip)
		fmt.Fprintf(w, "          mkdir -p \"%s\"\n", dir)
		fmt.Fprintf(w, "          curl -fsSL %s -o \"$RUNNER_TEMP/%s.download\"\n", shq(fill(t.URL)), t.Name)
		fmt.Fprintf(w, "          echo \"%s  $RUNNER_TEMP/%s.download\" | sha256sum -c -\n", sum, t.Name)
		fmt.Fprintf(w, "          %s\n", unpackCommand(fill(t.URL), "$RUNNER_TEMP/"+t.Name+".download", dir, t.Name))
		mounts = append(mounts, fmt.Sprintf("-v \"%s:/opt/starci/tools/%s:ro\"", dir, t.Name))
		for _, b := range t.Bin {
			pathDirs = append(pathDirs, path.Join("/opt/starci/tools", t.Name, fill(b)))
		}
	}

	image := s.Image
	if len(s.Packages) > 0 {
		image = "starci-env-" + id
		fmt.Fprintf(w, "      - name: Image with %s\n%s        run: |\n", strings.Join(s.Packages, ", "), skip)
		fmt.Fprintf(w, "          docker build -q -t %s - <<'DOCKERFILE'\n", image)
		fmt.Fprintf(w, "          FROM %s\n", s.Image)
		fmt.Fprintf(w, "          RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends %s && rm -rf /var/lib/apt/lists/*\n", strings.Join(s.Packages, " "))
		w.WriteString("          DOCKERFILE\n")
	}

	for _, name := range sortedKeys(s.Caches) {
		dir := "${{ runner.temp }}/starci-cache/" + name
		fmt.Fprintf(w, "      - name: %s\n%s        uses: actions/cache@v4\n        with:\n          path: %s\n          key: starci-cache-%s-${{ github.run_id }}\n          restore-keys: starci-cache-%s-\n",
			q("Cache: "+name), skip, dir, name, name)
		mounts = append(mounts, fmt.Sprintf("-v \"$RUNNER_TEMP/starci-cache/%s:%s\"", name, s.Caches[name]))
	}

	// A run can be tried again on a runner that is kept, so the attempt is
	// part of what the services and their network are called.
	network := "starci-$GITHUB_RUN_ID-${GITHUB_RUN_ATTEMPT:-1}-" + id
	if len(s.Services) > 0 {
		fmt.Fprintf(w, "      - name: %s\n%s        run: |\n", q("Services: "+strings.Join(serviceNames(s), ", ")), skip)
		for _, l := range startServices(s, network) {
			fmt.Fprintf(w, "          %s\n", l)
		}
	}

	// The command travels in an environment variable, so that nothing in it
	// needs escaping for the shell that starts the container.
	fmt.Fprintf(w, "      - name: %s\n%s        env:\n          STARCI_RUN: %s\n        run: |\n", q(s.Name), skip, block(s.Run, "            "))
	var args []string
	args = append(args, "-v \"$PWD:/workspace\"", "-w /workspace")
	switch {
	case len(s.Services) > 0:
		args = append(args, fmt.Sprintf("--network \"%s\"", network))
	case s.Offline:
		args = append(args, "--network none")
	}
	args = append(args, mounts...)
	if len(pathDirs) > 0 {
		base := "$image_path"
		if p, ok := s.Env["PATH"]; ok {
			base = p
		} else {
			if len(s.Packages) == 0 {
				fmt.Fprintf(w, "          docker pull -q %s\n", image)
			}
			// Tools go in front of the image's own PATH, which has to be asked for.
			fmt.Fprintf(w, "          image_path=$(docker image inspect %s --format '{{range .Config.Env}}{{println .}}{{end}}' | sed -n 's/^PATH=//p')\n", image)
		}
		args = append(args, fmt.Sprintf("-e \"PATH=%s:%s\"", strings.Join(pathDirs, ":"), base))
	}
	for _, k := range sortedKeys(s.Env) {
		if k == "PATH" && len(pathDirs) > 0 {
			continue
		}
		args = append(args, "-e "+shq(k+"="+s.Env[k]))
	}
	w.WriteString("          docker run --rm \\\n")
	for _, a := range args {
		fmt.Fprintf(w, "            %s \\\n", a)
	}
	fmt.Fprintf(w, "            %s sh -c \"$STARCI_RUN\"\n", image)

	if len(s.Services) > 0 {
		// Whatever became of the step: a runner that is kept would otherwise
		// keep its services too.
		always := "always()"
		if s.Cache {
			always += " && steps.passed.outputs.cache-hit != 'true'"
		}
		fmt.Fprintf(w, "      - name: Stop the services\n        if: %s\n        run: |\n", always)
		for _, l := range stopServices(s, network) {
			fmt.Fprintf(w, "          %s\n", l)
		}
	}
	if s.Cache {
		fmt.Fprintf(w, "      - name: Remember this pass\n%s        run: mkdir -p \"$RUNNER_TEMP/starci-passed\" && date > \"$RUNNER_TEMP/starci-passed/at\"\n", skip)
	}
	return nil
}

func serviceNames(s plan.Step) []string {
	names := make([]string, len(s.Services))
	for i, sv := range s.Services {
		names[i] = sv.Name
	}
	return names
}

// startServices is the shell that does for a job what a worker does for a
// step with services: a network for this job alone, each service on it under
// its own name, and no going on until each says it is ready. network is the
// network's name, as shell: it may hold variables.
func startServices(s plan.Step, network string) []string {
	create := "docker network create "
	if s.Offline {
		// Without the network a step still reaches its services, and they
		// reach nothing else either.
		create += "--internal "
	}
	lines := []string{fmt.Sprintf("%s\"%s\"", create, network)}
	for _, sv := range s.Services {
		run := fmt.Sprintf("docker run -d --name \"%s-%s\" --network \"%s\" --network-alias %s --hostname %s", network, sv.Name, network, sv.Name, sv.Name)
		for _, k := range sortedKeys(sv.Env) {
			run += " -e " + shq(k+"="+sv.Env[k])
		}
		run += " " + sv.Image
		for _, a := range sv.Args {
			run += " " + shq(a)
		}
		lines = append(lines, run)
	}
	for _, sv := range s.Services {
		if sv.Ready == "" {
			continue
		}
		// Two minutes, as a worker allows, by the clock: a try that hangs is
		// cut short, and counts against the same two minutes.
		lines = append(lines,
			"until=$(($(date +%s) + 120))",
			fmt.Sprintf("until timeout 10 docker exec \"%s-%s\" sh -c %s; do", network, sv.Name, shq(sv.Ready)),
			"  if [ \"$(date +%s)\" -ge \"$until\" ]; then",
			fmt.Sprintf("    echo \"service %s was not ready after 2 minutes\"", sv.Name),
			fmt.Sprintf("    docker logs --tail 20 \"%s-%s\"", network, sv.Name),
			"    exit 1",
			"  fi",
			"  sleep 0.5",
			"done")
	}
	return lines
}

func stopServices(s plan.Step, network string) []string {
	var lines []string
	for _, sv := range s.Services {
		lines = append(lines, fmt.Sprintf("docker rm -f -v \"%s-%s\" || true", network, sv.Name))
	}
	return append(lines, fmt.Sprintf("docker network rm \"%s\" || true", network))
}

// stepKey is everything about a step, other than its inputs' contents, that
// decides its outcome. It goes into the cache key so that changing a step's
// command or tools is a reason to run it again.
func stepKey(s plan.Step, arch string) string {
	var tools [][]string
	for _, t := range s.Tools {
		tools = append(tools, append([]string{t.Name, t.SHA256[arch]}, t.Bin...))
	}
	env := [][2]string{}
	for _, k := range sortedKeys(s.Env) {
		env = append(env, [2]string{k, s.Env[k]})
	}
	parts := []any{s.Image, arch, s.Run, env, tools, s.Packages, s.Inputs}
	// Only said when it is off, so that every other step keeps its key.
	if s.Offline {
		parts = append(parts, "offline")
	}
	// Likewise only said when there are some. A service's image is known
	// here by its name alone, as the step's is: nothing has been pulled.
	if len(s.Services) > 0 {
		parts = append(parts, "services", s.Services)
	}
	material, _ := json.Marshal(parts)
	sum := sha256.Sum256(material)
	return hex.EncodeToString(sum[:])[:16]
}

func isPattern(in string) bool { return strings.ContainsAny(in, "*?[") }

// sparsePattern writes an input as a sparse-checkout pattern, anchored at the
// top of the repository as inputs are.
func sparsePattern(in string) string {
	return "/" + in
}

// hashGlobs writes inputs as the globs hashFiles understands. A plain path
// may be a file or a directory, and only the checkout knows which, so both
// readings are given; the one that matches nothing adds nothing.
func hashGlobs(inputs []string) []string {
	var globs []string
	for _, in := range inputs {
		switch {
		case in == ".":
			return []string{"'**'", "'!.git/**'"}
		case isPattern(in):
			globs = append(globs, "'"+in+"'")
		default:
			globs = append(globs, "'"+in+"'", "'"+in+"/**'")
		}
	}
	return globs
}

func unpackCommand(url, file, dir, name string) string {
	lower := strings.ToLower(strings.SplitN(url, "?", 2)[0])
	switch {
	case strings.HasSuffix(lower, ".zip"):
		return fmt.Sprintf("unzip -q \"%s\" -d \"%s\"", file, dir)
	case strings.Contains(lower, ".tar.") || strings.HasSuffix(lower, ".tgz") || strings.HasSuffix(lower, ".tar"):
		return fmt.Sprintf("tar -xf \"%s\" -C \"%s\"", file, dir)
	}
	return fmt.Sprintf("install -m 755 \"%s\" \"%s/%s\"", file, dir, name)
}

// q writes a string as a YAML scalar. JSON's quoting is valid YAML and leaves
// no room for a value to be read as anything but a string.
func q(s string) string {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false) // & and < are not special here
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

// block writes a command as a YAML block, which keeps it readable and exactly
// as written. A command it cannot represent faithfully is quoted instead.
func block(s string, indent string) string {
	if s == "" || s != strings.TrimSpace(s) || strings.ContainsAny(s, "\r\t") || strings.HasPrefix(s, " ") {
		return q(s)
	}
	for _, line := range strings.Split(s, "\n") {
		if line != strings.TrimRight(line, " ") {
			return q(s)
		}
	}
	return "|-\n" + indent + strings.ReplaceAll(s, "\n", "\n"+indent)
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = q(s)
	}
	return out
}

// shq quotes a string for a POSIX shell.
func shq(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func wrap(text string, width int) []string {
	var lines []string
	line := ""
	for _, word := range strings.Fields(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}
