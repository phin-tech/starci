const sum = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"

func compileScript(t *testing.T, src string, o Options) string {
	t.Helper()
	p, read, err := plan.EvalTracked("ci.star", []byte(src), plan.Context{})
	if err != nil {
		t.Fatal(err)
	}
	o.Read = read
	out, err := GitHub(p, o)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func wants(t *testing.T, out string, fragments ...string) {
	t.Helper()
	for _, f := range fragments {
		if !strings.Contains(out, f) {
			t.Errorf("the workflow is missing:\n%s\n\nin:\n%s", f, out)
		}
	}
}

const script = `
uv = tool("uv", url = "https://example.com/uv-{arch}.tar.gz", sha256 = {"amd64": "` + sum + `"},
          arch_names = {"amd64": "x86_64"}, bin = ["uv-{arch}"])

def ci(ctx):
    lint = step("lint", image = "debian:12-slim", tools = [uv], run = "uv run ruff check app",
                inputs = ["app/**/*.py", "pyproject.toml"])
    test = step("API tests", image = "debian:12-slim", tools = [uv], packages = ["postgresql"],
                run = "uv run pytest -q && echo 'it''s done'", env = {"MODE": "ci"},
                inputs = ["app", "tests"], caches = {"uv": "/root/.cache/uv"}, needs = [lint])
    return [lint, test]
`

func TestStepsBecomeJobs(t *testing.T) {
	out := compileScript(t, script, Options{Source: "ci.star"})
	wants(t, out,
		"# Generated by `starci compile` from ci.star.",
		"  lint:\n    name: \"lint\"\n    runs-on: ubuntu-latest\n",
		// A name that is not a valid id still gets one, and needs follows it.
		"  api-tests:\n    name: \"API tests\"\n    runs-on: ubuntu-latest\n    needs: [lint]\n",
		// Only the inputs are checked out.
		"          sparse-checkout: |\n            /app/**/*.py\n            /pyproject.toml\n",
		// The tool, for the runner's architecture, verified before use.
		"curl -fsSL 'https://example.com/uv-x86_64.tar.gz'",
		`echo "`+sum+`  $RUNNER_TEMP/uv.download" | sha256sum -c -`,
		`-e "PATH=/opt/starci/tools/uv/uv-x86_64:$image_path"`,
		// Packages become an image built for the job.
		"FROM debian:12-slim\n          RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends postgresql",
		"starci-env-api-tests sh -c \"$STARCI_RUN\"",
		// The command is carried exactly as written.
		"          STARCI_RUN: |-\n            uv run pytest -q && echo 'it''s done'\n",
		"-e 'MODE=ci'",
		`-v "$RUNNER_TEMP/starci-cache/uv:/root/.cache/uv"`,
	)
}

func TestAJobSkipsWhenItsInputsAreUnchanged(t *testing.T) {
	out := compileScript(t, script, Options{})
	wants(t, out,
		"        id: passed\n        uses: actions/cache@v4\n",
		// A plain path may be a file or a directory; both readings are hashed.
		"hashFiles('app/**/*.py', 'pyproject.toml', 'pyproject.toml/**')",
		"hashFiles('app', 'app/**', 'tests', 'tests/**')",
		"        if: steps.passed.outputs.cache-hit != 'true'\n",
		"      - name: Remember this pass\n",
	)

	// Changing the command changes the key, so the job runs again.
	changed := compileScript(t, strings.Replace(script, "ruff check app", "ruff check app tests", 1), Options{})
	key := func(s string) string {
		i := strings.Index(s, "key: starci-passed-lint-")
		return s[i : i+50]
	}
	if key(out) == key(changed) {
		t.Errorf("the pass key did not change with the command: %s", key(out))
	}

	// So does taking the network away, and the container is started without it.
	sealed := compileScript(t, strings.Replace(script, `ruff check app",`, `ruff check app", network = False,`, 1), Options{})
	if key(out) == key(sealed) {
		t.Errorf("the pass key did not change with the network: %s", key(out))
	}
	if strings.Contains(out, "--network") || !strings.Contains(sealed, "            --network none \\\n") {
		t.Errorf("network = False did not become --network none on that step alone:\n%s", sealed)
	}

	// A step that must always run keeps no record of passing.
	live := compileScript(t, `
def ci(ctx):
    return [step("deploy", image = "alpine:3", run = "./deploy.sh", cache = False)]
`, Options{})
	if strings.Contains(live, "starci-passed") || strings.Contains(live, "cache-hit") {
		t.Errorf("a cache = False step was given a way to be skipped:\n%s", live)
	}
}

func TestWhatCannotBeCompiledIsSaid(t *testing.T) {
	out := compileScript(t, `
def ci(ctx):
    if ctx.ref == "main" and ctx.changed_files:
        return []
    return [
        step("gpu", image = "alpine:3", run = "true", worker = {"gpu": "true"}),
        step("picky", image = "alpine:3", run = "true", prefer = {"speed": "fast"}),
    ]
`, Options{})
	wants(t, out,
		"The script reads ctx.ref, so its plan depends on the commit.",
		"`prefer` and `avoid` have no equivalent here and are dropped (picky).",
		`    runs-on: ["self-hosted", "gpu=true"]`,
	)

	plain := compileScript(t, `
def ci(ctx):
    return [step("a", image = "alpine:3", run = "true")]
`, Options{})
	if strings.Contains(plain, "depends on the commit") {
		t.Error("a script that ignores ctx was said to depend on the commit")
	}
}

func TestAToolMustExistForTheRunnersArchitecture(t *testing.T) {
	p, _, err := plan.EvalTracked("ci.star", []byte(script), plan.Context{})
	if err != nil {
		t.Fatal(err)
	}
	_, err = GitHub(p, Options{Arch: "arm64", RunsOn: "ubuntu-24.04-arm"})
	if err == nil || !strings.Contains(err.Error(), `tool "uv" has no build for arm64`) {
		t.Fatalf("error = %v", err)
	}
}

// Every basic example compiles, and where actionlint is installed, what it
// compiles to is a workflow actionlint accepts.
func TestExamplesCompile(t *testing.T) {
	files, _ := filepath.Glob(filepath.Join("..", "..", "examples", "basic", "*.star"))
	if len(files) == 0 {
		t.Fatal("no examples found")
	}
	lint, _ := exec.LookPath("actionlint")
	// The examples' own runner labels are not ones actionlint knows.
	config := filepath.Join(t.TempDir(), "actionlint.yaml")
	os.WriteFile(config, []byte("self-hosted-runner:\n  labels: [\"gpu=true\", \"site=office\"]\n"), 0o644)

	for _, file := range files {
		t.Run(filepath.Base(file), func(t *testing.T) {
			src, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			p, read, err := plan.EvalTracked(file, src, plan.Context{})
			if err != nil {
				t.Fatal(err)
			}
			out, err := GitHub(p, Options{Source: filepath.Base(file), Read: read})
			if err != nil {
				t.Fatal(err)
			}
			if lint == "" {
				return
			}
			path := filepath.Join(t.TempDir(), "ci.yml")
			os.WriteFile(path, []byte(out), 0o644)
			if msg, err := exec.Command(lint, "-config-file", config, path).CombinedOutput(); err != nil {
				t.Errorf("actionlint rejects the workflow:\n%s", msg)
			}
		})
	}
}

// A step's secrets become the repository's secrets of the same names, and a
// job that has not been given one stops before its container starts.
func TestSecretsAreCompiled(t *testing.T) {
	const script = `
def ci(ctx):
    test = step("test", image = "alpine:3", run = "true")
    if ctx.event == "pull_request" and ctx.pr.fork:
        return [test]
    return [test, step("publish", image = "alpine:3", run = "npm publish", secrets = ["NPM_TOKEN"], needs = [test], cache = False)]
`
	out, err := GitHubEvents("ci.star", []byte(script), Options{Source: "ci.star"})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"NPM_TOKEN: ${{ secrets.NPM_TOKEN }}",
		`[ -n "${NPM_TOKEN:-}" ] || { echo "starci: this run has not been given the secret NPM_TOKEN"; exit 1; }`,
		"-e NPM_TOKEN \\",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("the workflow lacks %q:\n%s", want, out)
		}
	}

	// A step that asks for secrets whatever the event is one job, though for
	// a fork it is marked as not to be given them.
	always := strings.Replace(script, "    if ctx.event == \"pull_request\" and ctx.pr.fork:\n        return [test]\n", "", 1)
	if _, err := GitHubEvents("ci.star", []byte(always), Options{Source: "ci.star"}); err != nil {
		t.Errorf("a step with secrets for every event: %v", err)
	}

	p, err := plan.Eval("ci.star", []byte(script), plan.Context{})
	if err != nil {
		t.Fatal(err)
	}
	circle, err := CircleCI(p, Options{Source: "ci.star"})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(circle, "-e NPM_TOKEN") || !strings.Contains(circle, "has not been given the secret NPM_TOKEN") {
		t.Errorf("the CircleCI configuration does not pass the secret on:\n%s", circle)
	}
}
