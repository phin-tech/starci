func compileTemporal(t *testing.T, src string) map[string]string {
	t.Helper()
	files, err := Temporal("ci.star", []byte(src), Options{Source: "ci.star"})
	if err != nil {
		t.Fatal(err)
	}
	return files
}

func TestTemporalNeedsBecomeIndexes(t *testing.T) {
	plan := compileTemporal(t, `
def ci(ctx):
    return [
        step("build", image = "alpine:3", run = "true"),
        step("test", image = "alpine:3", run = "true", needs = ["build"]),
    ]
`)["plan.go"]
	wants(t, plan, `Name:   "test"`)
	wants(t, plan, "Needs:  []int{0},")
	wants(t, plan, `"number":2,"step":{"name":"test"`)
	if strings.Contains(plan, "when:") {
		t.Errorf("a step that runs on every event has a condition:\n%s", plan)
	}
}

func TestTemporalStepsForSomeEventsHaveConditions(t *testing.T) {
	plan := compileTemporal(t, `
def ci(ctx):
    steps = [step("build", image = "alpine:3", run = "true")]
    if ctx.event == "tag":
        steps.append(step("publish", image = "alpine:3", run = "true", needs = ["build"]))
    if ctx.event == "pull_request" and not ctx.pr.fork:
        steps.append(step("preview", image = "alpine:3", run = "true"))
    return steps
`)["plan.go"]
	wants(t, plan, `return c.Event == "tag"`)
	wants(t, plan, `c.Event == "pull_request" && !c.fork()`)
}

func TestTemporalQueuesAreNamedByTheMachinesAStepAsksFor(t *testing.T) {
	plan := compileTemporal(t, `
def ci(ctx):
    return [
        step("any", image = "alpine:3", run = "true"),
        step("train", image = "alpine:3", run = "true", on = {"gpu": "a100", "os": "linux"}),
    ]
`)["plan.go"]
	wants(t, plan, `Queue:  "starci",`)
	wants(t, plan, `Queue:  "starci/gpu=a100,os=linux",`)
}

func TestTemporalSaysWhatItDrops(t *testing.T) {
	plan := compileTemporal(t, `
def ci(ctx):
    return [step("build", image = "alpine:3", run = "true", prefer = {"fast": "yes"})]
`)["plan.go"]
	wants(t, plan, "`prefer` and `avoid` are dropped (build)")
}

// A step handed an artifact travels with its placeholder, for starci step to
// resolve from what the workflow gives it.
func TestTemporalHandsOnArtifacts(t *testing.T) {
	plan := compileTemporal(t, `
def ci(ctx):
    build = step("build", image = "alpine:3", run = "make", keep = ["out"])
    return [build, step("ship", image = "alpine:3", run = "ls in", artifacts = {"in": artifact(build, "out")})]
`)["plan.go"]
	wants(t, plan, `"artifacts":{"in":{"from":"build","path":"out"}}`)
	wants(t, plan, "Steps that keep files (build) hand them on")
}

func TestTemporalModuleIsPinned(t *testing.T) {
	files := compileTemporal(t, `
def ci(ctx):
    return [step("build", image = "alpine:3", run = "true")]
`)
	wants(t, files["go.mod"], "go.temporal.io/sdk "+temporalSDK)
	for name, text := range files {
		if strings.HasSuffix(name, ".go") && !strings.HasPrefix(text, "// Code generated by `starci compile --target temporal`") {
			t.Errorf("%s does not say it is generated", name)
		}
	}
}

func TestEveryBasicExampleCompilesForTemporal(t *testing.T) {
	scripts, _ := filepath.Glob(filepath.Join("..", "..", "examples", "basic", "*.star"))
	for _, file := range scripts {
		src, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := Temporal(file, src, Options{}); err != nil {
			t.Errorf("%s: %v", filepath.Base(file), err)
		}
	}
}

// The files must build against the SDK, and the workflow must do what the
// plan says. That needs the SDK, which is downloaded, so it runs when asked.
func TestTemporalModuleBuildsAndRuns(t *testing.T) {
	if os.Getenv("STARCI_TEST_TEMPORAL") == "" {
		t.Skip("set STARCI_TEST_TEMPORAL=1 to build the generated module against the Temporal SDK (needs the network)")
	}
	files := compileTemporal(t, `
def ci(ctx):
    steps = [
        step("build", image = "alpine:3", run = "true"),
        step("lint", image = "alpine:3", run = "true", needs = ["build"]),
        step("test", image = "alpine:3", run = "true", needs = ["build"]),
        step("ship", image = "alpine:3", run = "true", artifacts = {"in": artifact("build", "out")}),
    ]
    steps[0] = step("build", image = "alpine:3", run = "true", keep = ["out"])
    if ctx.event == "tag":
        steps.append(step("publish", image = "alpine:3", run = "true", needs = ["lint", "test"]))
    return steps
`)
	dir := t.TempDir()
	for name, text := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	tests, err := os.ReadFile(filepath.Join("testdata", "temporal", "starci_test.go.txt"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "starci_test.go"), tests, 0o644); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{{"mod", "tidy"}, {"vet", "./..."}, {"test", "./..."}} {
		cmd := exec.Command("go", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
		}
	}
}
